const fnv = (s: string): number => {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
};

export const lorem = (length: number, seed: string): string => {
  if (length <= 0) return "";
  let h = fnv(seed);
  let out = "";
  while (out.length < length) {
    out += (out ? " " : "") + WORDS[h % WORDS.length];
    h = (Math.imul(h, 1103515245) + 12345) >>> 0;
  }
  return out.slice(0, length);
};

const loremSegment = (stem: string): string => {
  return lorem(stem.length, stem).replace(/ /g, "-");
};

const neutralSegment = (seg: string): boolean => {
  if (!seg || KEEP_SEGMENTS.has(seg) || KEEP_SEGMENT_FORM.test(seg)) return true;
  const stem = (seg.match(SEGMENT_EXT)?.[1] ?? seg).replace(/^\./, "");
  return stem.split("-").every((t) => WORDS.some((w) => w.startsWith(t)));
};

const maskSegment = (seg: string): string => {
  if (neutralSegment(seg)) return seg;
  const dot = seg.startsWith(".") ? "." : "";
  const body = seg.slice(dot.length);
  const ext = body.match(SEGMENT_EXT);
  return ext ? `${dot}${loremSegment(ext[1] ?? "")}${ext[2]}` : `${dot}${loremSegment(body)}`;
};

const maskTail = (tail: string): string => tail.split("/").map(maskSegment).join("/");

const maskEncodedTail = (tail: string): string =>
  tail
    .split("-")
    .map((t) => (t === "" || neutralSegment(t) || /^(?:0[0-9a-f]*|\d+|home|user|proj)$/.test(t) ? t : loremSegment(t)))
    .join("-");

const badTail = (tail: string): boolean => tail.split("/").some((seg) => !neutralSegment(seg));

const encodeDir = (path: string): string => path.replace(/[^A-Za-z0-9]/g, "-");
const escapeRe = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const wordRe = (words: string[]): RegExp | null => (words.length ? new RegExp(`(?<![A-Za-z0-9])(?:${words.map(escapeRe).join("|")})(?![A-Za-z0-9])`, "gi") : null);

export const createMasker = (options: MaskOptions): Masker => {
  const remap = new Map<string, string>();
  const counters: Record<string, number> = {};
  const projects = new Map<string, string>();
  const roots = [...options.roots].sort((a, b) => b.length - a.length);
  const identityRe = wordRe([...new Set(options.extras.filter((e) => e.length > 1))]);
  const hostRe = wordRe([...new Set(options.hostnames.filter((e) => e.length > 1))]);
  const privateRe = wordRe([...new Set(options.privateNames.filter((e) => e.length > 1))]);

  const remapped = (kind: string, original: string, build: (n: number) => string): string => {
    const k = `${kind}:${original}`;
    let v = remap.get(k);
    if (!v) {
      counters[kind] = (counters[kind] ?? 0) + 1;
      v = build(counters[kind]);
      remap.set(k, v);
    }
    return v;
  };
  const project = (key: string): string => {
    let v = projects.get(key);
    if (!v) {
      v = `proj-${projects.size + 1}`;
      projects.set(key, v);
    }
    return v;
  };

  const shift = (iso: string, offset: number): string => {
    const out = new Date(Date.parse(iso) + offset).toISOString();
    return iso.includes(".") ? out : out.replace(/\.\d{3}Z$/, "Z");
  };

  const maskPath = (p: string): string => {
    const m = p.match(/^(?:\/home|\/Users)\/([^/]+)(\/.*)?$/);
    if (!m) return p;
    const rest = m[2] ?? "";
    const parts = rest.split("/").filter(Boolean);
    if (!parts.length) return MASK_HOME;
    if (parts[0]?.startsWith(".")) return `${MASK_HOME}/${parts[0]}${parts.length > 1 ? `/${maskTail(parts.slice(1).join("/"))}` : ""}`;
    const full = p.replace(/\/+$/, "");
    const root = roots.find((r) => full === r || full.startsWith(`${r}/`));
    if (root) return `${MASK_HOME}/${project(root)}${maskTail(full.slice(root.length))}`;
    const head = Math.min(2, parts.length);
    const tail = maskTail(parts.slice(head).join("/"));
    return `${MASK_HOME}/${project(parts.slice(0, head).join("/"))}${tail ? `/${tail}` : ""}`;
  };

  const maskEncodedDirs = (s: string): string => {
    let out = s;
    for (const r of roots) out = out.split(encodeDir(r)).join(encodeDir(maskPath(r)));
    return out.replace(/-(?:home|Users)-[A-Za-z0-9]+((?:-+(?!(?:home|Users)-)[A-Za-z0-9_.]+)*)/g, (whole, tail: string) => {
      if (tail.startsWith("--")) return `-home-user${maskEncodedTail(tail)}`;
      if (whole.startsWith("-home-user")) return whole;
      return tail ? `-home-user-${project(`enc:${tail}`)}` : "-home-user";
    });
  };

  const maskUrl = (u: string): string => {
    const m = u.match(/^https?:\/\/([^/\s:@]+@)?([^/\s:?#]+)/);
    if (!m || u.includes(PUBLIC_REPO)) return u;
    const host = (m[2] ?? "").toLowerCase();
    if (!m[1] && SAFE_URL_HOSTS.some((h) => host === h || host.endsWith(`.${h}`))) return host.endsWith("github.com") ? maskRepoUrl(u) : u;
    return remapped("url", u, (n) => `https://example.com/repo-${n}`);
  };

  const maskRepoUrl = (u: string): string =>
    u.replace(/^(https?:\/\/[^/]+\/)([^?#]*)/, (w, head: string, path: string) => (path.split("/").filter(Boolean).length < 3 ? w : head + path.split("/").map((seg) => (/^(?:\d+|issues|pull|pulls|discussions|blob|tree|commit|releases|tag|wiki|actions)?$/.test(seg) ? seg : loremSegment(seg))).join("/")));

  const generic = (s: string, offset: number): string => {
    let out = s;
    out = out.replace(/\bsk-[A-Za-z0-9_-]{16,}/g, REDACTED);
    out = out.replace(/\bgh[pousr]_[A-Za-z0-9]{16,}/g, REDACTED);
    out = out.replace(/\bglpat-[A-Za-z0-9_-]{8,}/g, REDACTED);
    out = out.replace(/\bxox[bap]-[A-Za-z0-9-]+/g, REDACTED);
    out = out.replace(/\bAKIA[0-9A-Z]{16}\b/g, REDACTED);
    out = out.replace(/\beyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/g, REDACTED);
    out = out.replace(/Bearer\s+\S+/g, `Bearer ${REDACTED}`);
    out = out.replace(/-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]*?(?:-----END [A-Z ]*PRIVATE KEY-----|$)/g, REDACTED);
    out = out.replace(/[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}/g, (e) => (/@(?:example\.com|users\.noreply\.github\.com)$/.test(e) ? e : MASK_EMAIL));
    out = out.replace(/https?:\/\/[^\s"'<>)\]]+/g, (u) => maskUrl(u));
    out = out.replace(/\bgitlab(?:\.[a-z0-9-]+)+\b/gi, (h) => (SAFE_URL_HOSTS.some((x) => h.toLowerCase().endsWith(x)) ? h : `gitlab.${MASK_HOSTNAME}`));
    out = out.replace(TEMP_DIR, "tmp").replace(UID_DIR, "claude-0");
    out = out.replace(USAGE_LINE, (w) => lorem(w.length, w)).replace(RESET_TEXT, (w) => lorem(w.length, w));
    out = out.replace(KERNEL, MASK_KERNEL).replace(IPV4, MASK_IPV4);
    out = maskEncodedDirs(out);
    out = out.replace(/(?:\/home|\/Users)\/[^\s"'`:;,)\]}<>\\]+/g, (p) => maskPath(p));
    if (identityRe) out = out.replace(identityRe, MASK_USER);
    if (hostRe) out = out.replace(hostRe, MASK_HOST);
    if (privateRe) out = out.replace(privateRe, (w, idx: number, whole: string) => (whole.startsWith(PUBLIC_REPO, idx) ? w : "proj"));
    out = out.replace(SESSION_FRAGMENT, "00000000");
    out = out.replace(UUID, (u) => remapped("uuid", u, (n) => `${SYNTH_UUID_PREFIX}${n.toString(16).padStart(12, "0")}`));
    out = out.replace(UUID_FRAGMENT, (f) => FRAGMENT_BASE.slice(0, f.length));
    out = out.replace(PREFIXED, (_w, p: string, body: string) => remapped(`id-${p}`, body, (n) => `${p}_${n.toString().padStart(body.length, "0")}`));
    out = out.replace(AGENT_ID, (_w, body: string) => remapped("agent", body, (n) => `agent-a${n.toString(16).padStart(body.length, "0")}`));
    out = out.replace(TILDE_PATH, (p) => {
      const parts = p.slice(2).split("/");
      const first = parts[0] ?? "";
      return `~/${[first.startsWith(".") ? first : loremSegment(first), ...parts.slice(1).map(maskSegment)].join("/")}`;
    });
    out = out.replace(ISO, (t) => shift(t, offset));
    out = out.replace(ISO_DASH, (t) => shift(`${t.slice(0, 10)}T${t.slice(11).replace(/-/g, ":")}Z`, offset).slice(0, 19).replace(/:/g, "-"));
    out = out.replace(/(cell ID )(\S+)/g, (_w, a: string, id: string) => `${a}${remapped("cell", id, (n) => `cell-${n}`)}`);
    return out;
  };

  const loremLines = (text: string, offset: number): string =>
    text
      .split("\n")
      .map((line) => {
        const prefix = STRUCT_PREFIXES.map((re) => line.match(re)).find(Boolean);
        if (prefix) {
          const head = prefix[0];
          const rest = line.slice(head.length);
          return generic(PATH_HEAD.test(head) ? line : head + lorem(rest.length, rest), offset);
        }
        const lead = line.match(/^\s*(?:[-+*>#]\s+|@@)?/)![0];
        const rest = line.slice(lead.length);
        return lead + lorem(rest.length, rest);
      })
      .join("\n");

  const textMask = (s: string, offset: number): string => {
    const stack: string[] = [];
    return s
      .split(/(<\/?[A-Za-z][\w:-]*(?:\s[^<>]*)?>)/)
      .map((tok) => {
        const tag = tok.match(/^<(\/?)([A-Za-z][\w:-]*)/);
        if (tag && tok.endsWith(">")) {
          if (tag[1]) stack.pop();
          else if (!tok.endsWith("/>")) stack.push(tag[2] ?? "");
          return generic(tok, offset);
        }
        if (!tok.trim()) return tok;
        const top = stack[stack.length - 1];
        return top && KEEP_TAGS.has(top) ? generic(tok, offset) : loremLines(tok, offset);
      })
      .join("");
  };

  const minTimestamp = (value: unknown): number => {
    if (typeof value === "string") return Math.min(Infinity, ...[...value.matchAll(ISO)].map((t) => Date.parse(t[0])));
    if (typeof value === "number") return value >= EPOCH_MS_MIN && value <= EPOCH_MS_MAX ? value : Infinity;
    if (Array.isArray(value)) return value.reduce((m: number, v) => Math.min(m, minTimestamp(v)), Infinity);
    if (value && typeof value === "object") return Object.values(value).reduce((m: number, v) => Math.min(m, minTimestamp(v)), Infinity);
    return Infinity;
  };

  const maskCommandArray = (arr: unknown[]): unknown[] => arr.map((w) => (typeof w === "string" ? (SHELL_WORDS.has(w) ? w : lorem(Math.min(w.length, 12), w)) : w));

  const maskString = (s: string, key: string, offset: number): string => {
    if (REDACT_KEYS.has(key) && s.length > 16) return REDACTED;
    if (KEEP_STRINGS.has(s)) return s;
    const t = s.trim();
    if ((t.startsWith("{") && t.endsWith("}")) || (t.startsWith("[") && t.endsWith("]"))) {
      try {
        return JSON.stringify(maskJsonValue(JSON.parse(t), key, offset));
      } catch {}
    }
    if (TIMEZONE.test(s) && key.toLowerCase().includes("timezone")) return MASK_TIMEZONE;
    if (HOST_KEYS.has(key) && /^[A-Za-z0-9.-]+\.[a-z]{2,}$/.test(s)) return MASK_HOSTNAME;
    if (SLUG_KEYS.has(key) && SLUG.test(s) && !s.startsWith("mcp__")) return s.split("-").map((w) => lorem(w.length, w)).join("-");
    if (CELL_KEYS.has(key)) return remapped("cell", s, (n) => `cell-${n}`);
    if (SECRET_KEY.test(key) && /^[A-Za-z0-9+/=_-]{32,}$/.test(s)) return REDACTED;
    if (!/\s/.test(s)) {
      if (/^https?:\/\//.test(s) || /^\//.test(s) || PATH_KEYS.has(key)) return generic(s, offset);
      if (s.length > BLOB_MIN && !s.startsWith("-home-")) return REDACTED;
      return generic(s, offset);
    }
    const free = FREE_KEYS.has(key) ? s.length > FREE_TEXT_MIN : s.length > OTHER_TEXT_MIN;
    return free ? textMask(s, offset) : generic(s, offset);
  };

  function maskJsonValue(value: unknown, key: string, offset: number): unknown {
    if (typeof value === "string") return COMMAND_KEYS.has(key) ? "echo lorem" : maskString(value, key, offset);
    if (typeof value === "number") {
      if (value >= EPOCH_MS_MIN && value <= EPOCH_MS_MAX) return value + offset;
      if (value >= EPOCH_S_MIN && value <= EPOCH_S_MAX && EPOCH_S_KEY.test(key)) return value + Math.round(offset / 1000);
      return value;
    }
    if (Array.isArray(value)) return COMMAND_KEYS.has(key) ? maskCommandArray(value) : value.map((v) => maskJsonValue(v, key, offset));
    if (value && typeof value === "object") {
      const out: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(value)) out[/\/|-home-|-Users-/.test(k) ? generic(k, offset) : k] = maskJsonValue(v, k, offset);
      return out;
    }
    return value;
  }

  const maskText = (text: string, offset: number): string =>
    text
      .split("\n")
      .map((l) => generic(l, offset))
      .join("\n");

  const leaks = (text: string): string[] => {
    const found = LEAK_PATTERNS.filter(([, re]) => re.test(text)).map(([name]) => name);
    for (const m of text.matchAll(HOME_TAIL)) if (badTail(m[1]?.slice(1) ?? "")) found.push("path tail");
    for (const m of text.matchAll(TILDE_PATH)) {
      const [first = "", ...rest] = m[0].slice(2).split("/");
      if (!first.startsWith(".") && !neutralSegment(first)) found.push("home-relative path");
      else if (rest.some((seg) => !neutralSegment(seg))) found.push("path tail");
    }
    if (privateRe) for (const m of text.matchAll(new RegExp(privateRe.source, "gi"))) if (!text.startsWith(PUBLIC_REPO, m.index)) found.push("private project name");
    if (identityRe && new RegExp(identityRe.source, "i").test(text)) found.push("identity");
    if (hostRe && new RegExp(hostRe.source, "i").test(text)) found.push("hostname");
    return found;
  };

  return { maskJsonValue, maskText, maskName: generic, minTimestamp, leaks };
};

const walk = (dir: string): string[] => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));

const git = (args: string[]): string => {
  try {
    return execFileSync("git", args, { encoding: "utf8" }).trim();
  } catch {
    return "";
  }
};

const collectRoots = (files: string[]): string[] => {
  const roots = new Set<string>();
  const visit = (v: unknown, key: string): void => {
    if (typeof v === "string") {
      if (ROOT_KEYS.includes(key) && /^(?:\/home|\/Users)\/[^/]+\/\S+$/.test(v)) roots.add(v.replace(/\/+$/, ""));
    } else if (Array.isArray(v)) for (const x of v) visit(x, key);
    else if (v && typeof v === "object") for (const [k, x] of Object.entries(v)) visit(x, k);
  };
  for (const f of files.filter((n) => /\.jsonl?$/.test(n))) {
    const text = readFileSync(f, "utf8");
    for (const d of f.endsWith(".jsonl") ? text.split("\n").filter(Boolean) : [text]) {
      try {
        visit(JSON.parse(d), "");
      } catch {}
    }
  }
  return [...roots];
};

interface Provenance {
  source: string;
  harnessVersion: string;
  capturedAt: string;
  maskedBy: string;
}

export const run = (inDir: string, outDir: string, extras: string[], check: boolean, privateNames: string[] = []): number => {
  const names = [userInfo().username, git(["config", "user.name"]), git(["config", "user.email"]), ...extras].filter((n): n is string => Boolean(n));
  const hostnames = [hostname(), hostname().split(".")[0] ?? ""];
  if (check) {
    const masker = createMasker({ extras: names, hostnames, privateNames, roots: [] });
    let bad = 0;
    for (const f of walk(outDir)) {
      const found = masker.leaks(readFileSync(f, "utf8"));
      if (found.length) {
        bad++;
        console.error(`leak ${relative(outDir, f)}: ${found.join(", ")}`);
      }
    }
    return bad ? 1 : 0;
  }
  const sha = git(["rev-parse", "--short", "HEAD"]) || "unknown";
  const manifestPath = join(inDir, MANIFEST);
  const manifest: Record<string, Partial<Provenance>> = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")) : {};
  const rawFiles = walk(inDir)
    .filter((f) => relative(inDir, f) !== MANIFEST && relative(inDir, f).includes("/"))
    .sort();
  const masker = createMasker({ extras: names, hostnames, privateNames, roots: collectRoots(rawFiles) });
  const provenance: Record<string, Record<string, Provenance>> = {};
  let dropped = 0;
  let total = 0;
  for (const file of rawFiles) {
    const rel = relative(inDir, file);
    const [harnessName, ...restParts] = rel.split("/");
    const harness = harnessName ?? "";
    const text = readFileSync(file, "utf8");
    let masked: string;
    let offset: number;
    if (/\.jsonl?$/.test(file)) {
      const isLines = file.endsWith(".jsonl");
      const parsed: unknown[] = [];
      for (const d of isLines ? text.split("\n").filter((l) => l.trim()) : [text]) {
        try {
          parsed.push(JSON.parse(d));
        } catch {
          dropped++;
        }
      }
      const min = masker.minTimestamp(parsed);
      offset = Number.isFinite(min) ? TARGET_START_MS - min : 0;
      const out = parsed.map((p) => masker.maskJsonValue(p, "", offset));
      masked = isLines ? `${out.map((o) => JSON.stringify(o)).join("\n")}\n` : `${JSON.stringify(out[0] ?? null, null, 1)}\n`;
    } else {
      const min = masker.minTimestamp(text);
      offset = Number.isFinite(min) ? TARGET_START_MS - min : 0;
      masked = masker.maskText(text, offset);
    }
    const outRel = restParts.map((p) => masker.maskName(p, offset)).join("/");
    const rollout = outRel.match(/^sessions\/\d{4}\/\d\d\/\d\d\/(rollout-(\d{4})-(\d\d)-(\d\d)T.*)$/);
    const finalRel = rollout ? `sessions/${ROLLOUT_DIR}/${(rollout[1] ?? "").replace(/^rollout-\d{4}-\d\d-\d\dT\d\d-\d\d-\d\d/, `rollout-${ROLLOUT_STAMP}`)}` : outRel;
    const found = masker.leaks(masked);
    if (found.length || Buffer.byteLength(masked) > MAX_FILE_BYTES) {
      console.error(`refused ${rel}: ${found.join(", ") || "larger than the file cap"}`);
      return 1;
    }
    const dest = join(outDir, harness, finalRel);
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, masked);
    total += Buffer.byteLength(masked);
    const meta = manifest[rel] ?? {};
    (provenance[harness] ??= {})[finalRel] = {
      source: meta.source ?? "local-capture",
      harnessVersion: meta.harnessVersion ?? "unknown",
      capturedAt: meta.capturedAt ?? "2026-11-08",
      maskedBy: `${TOOL_PATH}@${sha}`,
    };
  }
  if (total > MAX_TREE_BYTES) {
    console.error("fixtures larger than the tree cap");
    return 1;
  }
  for (const [harness, entries] of Object.entries(provenance)) {
    const sorted = Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)));
    writeFileSync(join(outDir, harness, "provenance.json"), `${JSON.stringify(sorted, null, 1)}\n`);
  }
  console.log(`masked ${rawFiles.length} files, ${total} bytes, ${dropped} non-JSON lines dropped`);
  return 0;
};

if (import.meta.main) {
  const args = process.argv.slice(2);
  const flag = (name: string): string | undefined => {
    const i = args.indexOf(name);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const input = flag("--in") ?? "";
  const check = args.includes("--check");
  if (!check && !input) {
    console.error("usage: bun tools/mask-captures.ts --in <raw dir> --out <fixtures dir> [--extra a,b] [--private a,b] [--check]");
    process.exit(2);
  }
  const list = (name: string): string[] => (flag(name) ?? "").split(",").filter(Boolean);
  process.exit(run(input, flag("--out") ?? "packages/adapters/fixtures", list("--extra"), check, list("--private")));
}
