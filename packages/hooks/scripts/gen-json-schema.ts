import { join } from "node:path";
import { adapters } from "../src/adapters/index.ts";
import { emit, parseArgs } from "./lib/emit.ts";

const { check, root } = parseArgs();
const files = new Map<string, string>();
const owned: string[] = [];

const HARNESSES: Record<string, { title: string; common: string[]; always: string[]; intro: string }> = {
  claude: {
    title: "Claude Code",
    common: ["session_id", "transcript_path", "cwd", "hook_event_name", "prompt_id", "scratchpad_dir", "permission_mode", "effort", "agent_id", "agent_type"],
    always: ["agent_id", "agent_type"],
    intro:
      "Every event also carries `session_id`, `transcript_path`, `cwd` and `hook_event_name`, and may carry `prompt_id`, `scratchpad_dir`,\n" +
      "`permission_mode`, `effort`, `agent_id` and `agent_type`; the table lists only the keys specific to each event.",
  },
  codex: {
    title: "Codex",
    common: ["session_id", "transcript_path", "cwd", "hook_event_name"],
    always: [],
    intro:
      "Every event also carries `session_id`, `transcript_path` (null in ephemeral runs), `cwd` and `hook_event_name`;\n" +
      "the table lists only the keys specific to each event.",
  },
  opencode: {
    title: "OpenCode",
    common: ["session_id", "sessionID", "hook_event_name"],
    always: [],
    intro:
      "Bodies come from `clients/opencode/plugin.ts`: OpenCode's own hook arguments or event data, plus the plugin's `hook_event_name`\n" +
      "and `session_id` (a copy of OpenCode's `sessionID`). The file name is the event name; the table lists only the keys specific to each event.",
  },
};

type Js = { required?: string[]; properties?: Record<string, unknown> };
let total = 0;
for (const [id, adapter] of adapters) {
  const h = HARNESSES[id];
  if (!h) throw new Error(`gen-json-schema.ts has no entry for harness "${id}"`);
  const out = join(root, "schemas", id);
  owned.push(out);
  const common = new Set(h.common);
  const rows: string[] = [];
  for (const [name, schema] of Object.entries(adapter.jsonSchemas()).sort(([a], [b]) => a.localeCompare(b))) {
    files.set(join(out, `${name}.json`), JSON.stringify(schema, null, 2) + "\n");
    const s = schema as Js;
    const required = (s.required ?? []).filter((k) => !common.has(k) || h.always.includes(k));
    const optional = Object.keys(s.properties ?? {}).filter((k) => !required.includes(k) && !common.has(k));
    rows.push(`| ${name} | ${required.map((k) => `\`${k}\``).join(", ")} | ${optional.map((k) => `\`${k}\``).join(", ")} |`);
  }
  total += rows.length;
  files.set(
    join(out, "README.md"),
    [
      `# ${h.title} hook payloads`,
      "",
      `Generated by \`scripts/gen-json-schema.ts\` from \`src/adapters/${id}/events/\`. Do not edit by hand.`,
      "Every schema is open: unknown keys are allowed, and the server only reports `missing` and `wrong_type` in its log.",
      h.intro,
      "",
      "| Event | Required | Optional |",
      "| --- | --- | --- |",
      ...rows,
      "",
    ].join("\n"),
  );
}

const code = emit(files, check, owned, root);
if (!check && code === 0) console.log(`wrote ${total} schemas for ${adapters.size} harnesses under ${join(root, "schemas")}`);
process.exit(code);
