// Regenerates src/events/index.ts (handlers) and src/adapters/claude/schemas.ts (payload schemas)
// from the files in src/events/ and src/adapters/claude/events/ (every <Event>.ts except index/types).
// Usage: bun scripts/gen-registry.ts [--check] [--root <dir>]
// --check writes nothing: it exits 1 and lists the files that are stale. --root runs against another copy of the tree.
import { readdirSync } from "node:fs";
import { join } from "node:path";
import { emit, parseArgs } from "./lib/emit.ts";

const { check, root } = parseArgs();
const dir = join(root, "src", "events");
const names = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && !["index.ts", "types.ts"].includes(f))
  .map((f) => f.slice(0, -3))
  .sort();

// One payload schema per event, kept next to the Claude adapter. Every handler must have one.
const schemaDir = join(root, "src", "adapters", "claude", "events");
const schemaNames = readdirSync(schemaDir).filter((f) => f.endsWith(".ts")).map((f) => f.slice(0, -3)).sort();
const missing = names.filter((n) => !schemaNames.includes(n));
if (missing.length) throw new Error(`no payload schema for: ${missing.join(", ")}`);

const files = new Map<string, string>([
  [
    join(dir, "index.ts"),
    [
      "// Generated by scripts/gen-registry.ts. Do not edit by hand.",
      'import type { EventHandler } from "./types.ts";',
      ...names.map((n) => `import { handler as ${n} } from "./${n}.ts";`),
      "",
      "export const handlers: ReadonlyMap<string, EventHandler> = new Map([",
      ...names.map((n) => `  [${n}.event, ${n}],`),
      "]);",
      "",
    ].join("\n"),
  ],
  [
    join(schemaDir, "..", "schemas.ts"),
    [
      "// Generated by scripts/gen-registry.ts. Do not edit by hand.",
      'import type { z } from "zod";',
      ...schemaNames.map((n) => `import { schema as ${n} } from "./events/${n}.ts";`),
      "",
      "export const schemas: ReadonlyMap<string, z.ZodType> = new Map<string, z.ZodType>([",
      ...schemaNames.map((n) => `  ["${n}", ${n}],`),
      "]);",
      "",
    ].join("\n"),
  ],
]);

const code = emit(files, check, [], root);
if (!check && code === 0) console.log(`registered ${names.length} handlers and ${schemaNames.length} schemas`);
process.exit(code);
