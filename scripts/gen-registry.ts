// For every harness adapter, regenerates <adapter>/handlers/index.ts (the log-metadata handlers) and <adapter>/schemas.ts
// (the payload schemas) from the files in <adapter>/handlers/ and <adapter>/events/ (every <Event>.ts except index/types).
// Usage: bun scripts/gen-registry.ts [--check] [--root <dir>]
// --check writes nothing: it exits 1 and lists the files that are stale. --root runs against another copy of the tree.
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { emit, parseArgs } from "./lib/emit.ts";

/** The adapters that have per-event handlers and schemas. Adding a harness adds its folder name here. */
export const HARNESSES = ["claude", "codex", "opencode"];

const { check, root } = parseArgs();
const files = new Map<string, string>();
const summary: string[] = [];

for (const harness of HARNESSES) {
  const adapterDir = join(root, "src", "adapters", harness);
  const dir = join(adapterDir, "handlers");
  const names = readdirSync(dir)
    .filter((f) => f.endsWith(".ts") && !["index.ts", "types.ts"].includes(f))
    .map((f) => f.slice(0, -3))
    .sort();

  // One payload schema per event, kept next to the adapter. Every handler must have one, and every schema a handler.
  const schemaDir = join(adapterDir, "events");
  const schemaNames = readdirSync(schemaDir).filter((f) => f.endsWith(".ts")).map((f) => f.slice(0, -3)).sort();
  const noSchema = names.filter((n) => !schemaNames.includes(n));
  if (noSchema.length) throw new Error(`${harness}: no payload schema for: ${noSchema.join(", ")}`);
  const noHandler = schemaNames.filter((n) => !names.includes(n));
  if (noHandler.length) throw new Error(`${harness}: no handler for: ${noHandler.join(", ")}`);

  files.set(
    join(dir, "index.ts"),
    [
      "// Generated by scripts/gen-registry.ts. Do not edit by hand.",
      'import type { EventHandler } from "./types.ts";',
      ...names.map((n) => `import { handler as ${n} } from "./${n}.ts";`),
      "",
      "export const handlers: ReadonlyMap<string, EventHandler> = new Map([",
      ...names.map((n) => `  [${n}.event, ${n}],`),
      "]);",
      "",
    ].join("\n"),
  );
  // A schema file may say which event it serves (`export const event = "tool.execute.before"`) when the event name cannot be a file
  // name; otherwise the file name is the event name.
  const eventOf = (n: string): string => /export const event = "([^"]+)"/.exec(readFileSync(join(schemaDir, `${n}.ts`), "utf8"))?.[1] ?? n;
  files.set(
    join(adapterDir, "schemas.ts"),
    [
      "// Generated by scripts/gen-registry.ts. Do not edit by hand.",
      'import type { z } from "zod";',
      ...schemaNames.map((n) => `import { schema as ${n} } from "./events/${n}.ts";`),
      "",
      "export const schemas: ReadonlyMap<string, z.ZodType> = new Map<string, z.ZodType>([",
      ...schemaNames.map((n) => `  [${JSON.stringify(eventOf(n))}, ${n}],`),
      "]);",
      "",
    ].join("\n"),
  );
  summary.push(`${harness}: ${names.length} handlers and ${schemaNames.length} schemas`);
}

const code = emit(files, check, [], root);
if (!check && code === 0) console.log(`registered ${summary.join("; ")}`);
process.exit(code);
